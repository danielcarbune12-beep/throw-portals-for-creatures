-- WorldBuilder: builds ONE long map — the hub (bases + launch hall) and the 3200-stud throwing
-- lane split into 8 biome zones. Each biome lives in its own module (Biome<Id>) built with the
-- shared WorldKit; this file only orchestrates terrain, zones, markers and boundaries.
-- Location: ServerScriptService > Server > WorldBuilder (ModuleScript)

local ReplicatedStorage = game:GetService("ReplicatedStorage")
local Config = require(ReplicatedStorage.Shared.Config)
local K = require(script.Parent.WorldKit)
local Landmarks = require(script.Parent.WorldLandmarks)

local WorldBuilder = {}
local Terrain = workspace.Terrain
local W = Config.MapHalfWidth
local V3, CF = Vector3.new, CFrame.new

local folder
local function block(cf, size, color, mat, collide, transp)
	local p = Instance.new("Part")
	p.Size, p.CFrame, p.Color, p.Material = size, cf, color, mat or Enum.Material.SmoothPlastic
	p.Anchored, p.CanCollide, p.CanQuery, p.CanTouch = true, collide == true, collide == true, false
	p.Transparency = transp or 0
	p.TopSurface, p.BottomSurface = Enum.SurfaceType.Smooth, Enum.SurfaceType.Smooth
	p.Parent = folder
	return p
end
local function textLabel(parent, text, color, face) return K.textSurface(parent, text, color, face) end
WorldBuilder.textLabel = textLabel

---------------------------------------------------------------- biome modules
local BIOME_MODULES = {}
local function biomeModule(id)
	if BIOME_MODULES[id] == nil then
		local m = script.Parent:FindFirstChild("Biome" .. id)
		BIOME_MODULES[id] = m and require(m) or false
	end
	return BIOME_MODULES[id]
end

---------------------------------------------------------------- start area
local function isHubSpawn(instance)
	if not instance:IsA("SpawnLocation") then return false end
	if instance:GetAttribute("TPFCGenerated") then return true end
	-- Migrate only the exact invisible spawn generated by earlier versions.
	return instance.Name == "SpawnLocation" and instance.Transparency == 1
		and (instance.Position - V3(0, 0.6, -60)).Magnitude < 0.02
		and (instance.Size - V3(12, 1, 12)).Magnitude < 0.02
end
local function buildStart()
	local depth = Config.StartDepth
	local SW = Config.StartHalfWidth
	-- terrain voxels are 4 studs: a fill whose top is at y = -2 renders its surface at y ~ 0, which is
	-- where every flush detail and prop is authored (a top at 0 renders at ~2 and buries them)
	Terrain:FillBlock(CF(0, 14, -depth / 2 - 10), V3(SW * 2 + 80, 32, depth + 30), Enum.Material.Air)
	Terrain:FillBlock(CF(0, -8, -depth / 2 - 10), V3(SW * 2 + 80, 12, depth + 30), Enum.Material.Grass)
	K.SetFolder(folder)
	Landmarks.SetFolder(folder)
	Landmarks.SetTerrain(Terrain)
	local hub = script.Parent:FindFirstChild("WorldHub")
	if hub then
		require(hub).Build(folder, textLabel)
	else
		Landmarks.Hub(depth, SW, Config.HallBackZ)
	end
	-- spawn on the street, just behind the hall
	local spawn = Instance.new("SpawnLocation")
	spawn.Size = V3(12, 1, 12)
	spawn.CFrame = CF(0, 0.6, -60)
	spawn.Anchored = true
	spawn.Transparency = 1
	spawn.CanCollide = false
	spawn.Duration = 0
	spawn.Neutral = true
	spawn.Name = "SanctuarySpawn"
	spawn:SetAttribute("TPFCGenerated", true)
	spawn.Parent = workspace
end

---------------------------------------------------------------- distance markers (flush line + low stone post outside the reveal corridor)
local function distanceMarker(z)
	local line = block(CF(0, 0.08, z), V3(Config.LaneHalfWidth * 2, 0.12, 0.6), Color3.new(1, 1, 1), Enum.Material.SmoothPlastic, false, 0.7)
	line.Name = "Marker"
	if z % 100 ~= 0 then return end
	for s = -1, 1, 2 do
		local x = s * 41
		block(CF(x, 1.2, z), V3(1.6, 2.4, 1.6), Color3.fromRGB(226, 220, 210), Enum.Material.Limestone)
		local plaque = block(CF(x, 2.9, z), V3(4.2, 1.6, 0.4), Color3.fromRGB(60, 44, 92), Enum.Material.SmoothPlastic)
		block(CF(x, 3.8, z), V3(4.4, 0.2, 0.5), Color3.fromRGB(232, 190, 90), Enum.Material.Metal)
		textLabel(plaque, z .. "m", Color3.fromRGB(255, 236, 190), Enum.NormalId.Front)
		textLabel(plaque, z .. "m", Color3.fromRGB(255, 236, 190), Enum.NormalId.Back)
	end
end

---------------------------------------------------------------- one zone
local function buildZone(map, id)
	local Wd = Config.Worlds[id]
	local b = Config.ZoneBounds[id]
	local m = Config.WorldCenter(id)
	local old = map:FindFirstChild(id)
	if old then old:Destroy() end
	folder = Instance.new("Folder"); folder.Name = id; folder.Parent = map
	K.SetFolder(folder)
	Terrain:SetMaterialColor(Wd.material, Wd.groundColor)
	-- valley floor (landing surface): the lane plus the walkable sides
	Terrain:FillBlock(CF(0, 14, m.Z), V3(W * 2 + 120, 32, b[2] - b[1] + 4), Enum.Material.Air)
	Terrain:FillBlock(CF(0, -8, m.Z), V3(W * 2 + 120, 12, b[2] - b[1] + 4), Wd.material)
	local mod = biomeModule(id)
	if mod then
		local ok, err = pcall(mod.Build, b, m.Z, { Config = Config, textLabel = textLabel, World = Wd })
		K.mirror = false
		if not ok then warn("[WorldBuilder] biome failed", id, err) end
	else
		Landmarks.SetFolder(folder)
		Landmarks.SetTerrain(Terrain)
		local ok, err = pcall(Landmarks.Biome[id], b, m.Z)
		if not ok then warn("[WorldBuilder] landmarks failed", id, err) end
		pcall(Landmarks.ZoneGate, Wd.name:upper() .. "  •  " .. b[1] .. "m", b[1] + 2, Wd.atmo, textLabel)
		if b[1] > 0 then pcall(Landmarks.Transition, id, b[1]) end
	end
end

function WorldBuilder.BuildAll()
	-- Saved Studio previews contain generated geometry. Replace that exact namespace
	-- on boot, rather than stacking another full map over it on every playtest.
	for _, old in ipairs(workspace:GetChildren()) do
		local generatedMap = old.Name == "Map" and old:IsA("Folder") and old:FindFirstChild("Start") and old:FindFirstChild("Forest")
		local generatedSpawn = isHubSpawn(old)
		if generatedMap or generatedSpawn then
			old:Destroy()
		end
	end
	local map = Instance.new("Folder")
	map.Name = "Map"
	map:SetAttribute("TPFCGenerated", true)
	map.Parent = workspace
	-- stylised look: no realistic grass blades; calm water
	pcall(function() Terrain.Decoration = false end)
	Terrain.WaterColor = Color3.fromRGB(60, 200, 215)
	Terrain.WaterTransparency = 0.55
	Terrain.WaterWaveSize = 0.08
	Terrain.WaterWaveSpeed = 6
	Terrain.WaterReflectance = 0.45
	Terrain:SetMaterialColor(Enum.Material.Glacier, Color3.fromRGB(150, 220, 255))
	Terrain:SetMaterialColor(Enum.Material.CrackedLava, Color3.fromRGB(255, 110, 30))
	Terrain:SetMaterialColor(Enum.Material.Rock, Color3.fromRGB(128, 128, 120))
	-- Terrain:SetMaterialColor is GLOBAL per material: every zone must own a distinct ground material
	local usedBy = {}
	for _, id in ipairs(Config.WorldOrder) do
		local mt = Config.Worlds[id].material
		if usedBy[mt] then warn("[WorldBuilder] terrain material shared by", usedBy[mt], "and", id, "- colours will conflict") end
		usedBy[mt] = id
	end
	folder = Instance.new("Folder"); folder.Name = "Start"; folder.Parent = map
	buildStart()
	for _, id in ipairs(Config.WorldOrder) do
		buildZone(map, id)
		task.wait()
	end
	folder = Instance.new("Folder"); folder.Name = "Markers"; folder.Parent = map
	for z = 50, Config.LaneLength - 50, 50 do distanceMarker(z) end
	-- invisible walls around the whole map
	local SW = Config.StartHalfWidth
	for s = -1, 1, 2 do
		block(CF(s * (W + 4), 80, Config.LaneLength / 2), V3(4, 200, Config.LaneLength + 20), Color3.new(1, 1, 1), nil, true, 1).Name = "Boundary"
		block(CF(s * (SW + 4), 80, -Config.StartDepth / 2), V3(4, 200, Config.StartDepth + 20), Color3.new(1, 1, 1), nil, true, 1).Name = "Boundary"
	end
	block(CF(0, 80, Config.LaneLength + 10), V3(W * 2 + 20, 200, 4), Color3.new(1, 1, 1), nil, true, 1).Name = "Boundary"
	block(CF(0, 80, -Config.StartDepth - 6), V3(SW * 2 + 20, 200, 4), Color3.new(1, 1, 1), nil, true, 1).Name = "Boundary"
end

-- Edit-time lobby iteration does not rebuild any biome or touch lane terrain.
function WorldBuilder.RebuildHub()
	local map = workspace:FindFirstChild("Map")
	assert(map and map:IsA("Folder"), "Build the map before rebuilding its lobby")
	local old = map:FindFirstChild("Start")
	if old then old:Destroy() end
	for _, spawn in ipairs(workspace:GetChildren()) do
		if isHubSpawn(spawn) then spawn:Destroy() end
	end
	folder = Instance.new("Folder"); folder.Name = "Start"; folder.Parent = map
	buildStart()
	return folder
end

-- dev/iteration: rebuild a single zone in place (Studio command bar / MCP)
function WorldBuilder.RebuildZone(id)
	local map = workspace:FindFirstChild("Map")
	if not map then return end
	BIOME_MODULES[id] = nil
	buildZone(map, id)
end

return WorldBuilder
